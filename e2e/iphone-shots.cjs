const env = require("./lib/env.cjs");
const path = require("path"); const fs = require("fs");
const { chromium, devices } = require("playwright");
const OUT = env.out("w13"); fs.mkdirSync(OUT, { recursive: true });
(async () => {
  const browser = await chromium.launch();
  const d = devices["iPhone 14"];
  const ctx = await browser.newContext({ viewport: d.viewport, userAgent: d.userAgent, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const p = await ctx.newPage();
  const errors = []; p.on("pageerror", (e) => errors.push(e.message));
  await p.goto(env.BASE + "/");
  await p.getByText("新增空白筆記本").waitFor();
  await p.screenshot({ path: path.join(OUT, "iphone-1-library.png") });
  await p.getByRole("button", { name: "橫線" }).click();
  await p.waitForFunction(() => document.querySelector(".reader__count")?.textContent === "/ 1");
  await p.waitForTimeout(500);
  await p.screenshot({ path: path.join(OUT, "iphone-2-notebook.png") });
  const b64 = await p.evaluate(() => { const c = document.createElement("canvas"); c.width = 300; c.height = 200; const x = c.getContext("2d"); x.fillStyle = "#16a34a"; x.fillRect(0, 0, 300, 200); return c.toDataURL("image/png").split(",")[1]; });
  await p.locator('input[aria-label="選擇要插入的圖片"]').setInputFiles({ name: "綠.png", mimeType: "image/png", buffer: Buffer.from(b64, "base64") });
  await p.locator(".note-image").waitFor();
  await p.waitForTimeout(300);
  await p.screenshot({ path: path.join(OUT, "iphone-3-image.png") });
  await p.locator(".reader__connect").click();
  await p.getByRole("button", { name: "邀請另一台裝置" }).click();
  await p.waitForTimeout(500);
  await p.screenshot({ path: path.join(OUT, "iphone-4-invite.png") });
  const overflow = await p.evaluate(() => ({ doc: document.documentElement.scrollWidth, win: innerWidth, toolbar: document.querySelector(".reader__toolbar").scrollWidth, ink: document.querySelector(".ink-toolbar").scrollWidth, inkClient: document.querySelector(".ink-toolbar").clientWidth }));
  console.log(JSON.stringify(overflow), errors);
  await browser.close();
})();
